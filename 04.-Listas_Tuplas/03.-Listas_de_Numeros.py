''' Existen métodos exclusivos para listas que contienen unicamente números, a continuación se muestran
    los principales'''

lista = [45, 123, 5, 9, 3, 1, 782, 25]
print(lista)

print(max(lista)) # La función máx se usa para extraer el número más grande de una lista

print(min(lista)) # La función min se usa para extraer el número más pequeño de una lista

print(sum(lista)) # La función sum se usa para sumar todos los elementos de una lista