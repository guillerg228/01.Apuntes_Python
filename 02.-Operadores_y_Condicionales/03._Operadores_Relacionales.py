'''Los operadores relaionales devuleven un valor booleano resultante de si se cumple
    o no la condición que se establece'''

numero1 = 3
numero2 = 8

res = numero1 > numero2         # Mayor a
print(numero1,'>',numero2,'?')
print(res)

res = numero1 < numero2         # Menor a
print(numero1,'<',numero2,'?')
print(res)

res = numero1 >= numero2        # Mayor o igual a
print(numero1,'>=',numero2,'?')
print(res)

res = numero1 <= numero2        # Menor o igual a
print(numero1,'<=',numero2,'?')
print(res)

res = numero1 == numero2        # Igual a
print(numero1,'=',numero2,'?')
print(res)

res = numero1 != numero2        # Diferente a
print(numero1,'!=',numero2,'?')
print(res)
