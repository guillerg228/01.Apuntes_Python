numero = 20  #Asignacion
print(numero)

numero += 5  #Se le suma 5
print(numero)

numero -= 3  #Se le resta 3
print(numero)

numero *= 2
print(numero)

numero /=2   #Se divide entre 2
print(numero)

numero %= 12  #Se le asigna el residuo de su divición entre 3
print(numero)

numero //= 3  #Se le asigna el resultado de su divición exacta entre 3
print(numero)

numero **= 2  #Se le asigna el resultado de elevarlo al cuadrado
print(numero)

