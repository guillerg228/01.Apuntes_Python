variable1 = int(input("Ingrese el número 1: "))
variable2 = int(input("Ingrese el número 2: "))

suma = variable1 + variable2
print(variable1,' + ',variable2,' = ', suma)

resta = variable1 - variable2
print(variable1,' - ',variable2,' = ', resta)

multi = variable1 * variable2
print(variable1,' * ',variable2,' = ', multi)

divi = variable1/variable2
print(variable1,' / ',variable2,' = ', divi)

modulo = variable1%variable2
print(variable1,' % ',variable2,' = ', modulo)

div_ex = variable1//variable2
print(variable1,' // ',variable2,' = ', div_ex)

variable1 = int(input("Ingrese la base: "))
